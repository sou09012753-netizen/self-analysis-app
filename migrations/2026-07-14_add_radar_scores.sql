-- 五角形レーダー用スコア
--
-- 形: {"1": {"生き方":4,"環境":3,"承認と動機":5,"行動":2,"自己コントロール":3}, "2": {...}, "3": {...}}
--
-- スコアの意味は「その領域で本人がどれだけ自分の言葉を出せたか（自己開示の深さ）」。
-- 能力・性格・優劣の評価ではない。1 = 未踏（まだ言葉が出ていない）。0は使わない。
--
-- ※ session_data(JSON) の中に持たせない理由：
--    /api/db/save.js はクライアントが持つ session_data を丸ごと upsert する（上書き競合が未修正）。
--    コーチがカード生成でスコアを書いた直後にクライアントがアプリを開くと、
--    スコアを知らない古い blob に上書きされて消える。answers が消えたのと同じ経路。
--    別列にすることで、あのデバウンス保存から完全に隔離される。

alter table public.coaching_users
  add column if not exists radar_scores jsonb not null default '{}'::jsonb;
